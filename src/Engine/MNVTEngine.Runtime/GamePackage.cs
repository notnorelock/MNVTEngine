namespace MNVTEngine.Runtime;

/// <summary>One file of an exported game, relative to the package root, with its SHA-256.</summary>
public sealed record PackagedFile(string Path, long Size, string Sha256);

/// <summary>What a content package holds (<see cref="ContentPackage.Kind"/>).</summary>
public static class ContentPackageKinds
{
    /// <summary>Runtime configuration, asset index, the game's C# code: needed before anything else.</summary>
    public const string Globals = "globals";

    /// <summary>Generated by the engine at build time, not authored: precompiled shaders (SPIR-V).</summary>
    public const string DefaultResources = "defaultResources";

    /// <summary>One scene and the assets only that scene uses.</summary>
    public const string Level = "level";

    /// <summary>Assets used by two or more scenes.</summary>
    public const string SharedAssets = "sharedAssets";

    /// <summary>Assets no scene references: loaded by path or GUID at run time (or unused).</summary>
    public const string Resources = "resources";
}

/// <param name="File">Package file name inside the data folder.</param>
/// <param name="Scene">For levels: the scene path relative to Assets. Build-time only: not written to the manifest, which is plain text.</param>
/// <param name="Entries">Number of files, for inspection.</param>
/// <param name="Guid">The package's GUID; the game refuses a package file with another one.</param>
/// <param name="HeaderSha256">SHA-256 of the package header, which covers its index and every chunk hash: identifies its exact content.</param>
public sealed record ContentPackage(string File, string Kind, [property: JsonIgnore] string? Scene = null, int Entries = 0, Guid Guid = default, string HeaderSha256 = "");

/// <summary>
/// Layout of an exported game and its build manifest, <c>&lt;Game&gt;_Data/package.json</c>: what was built, how, the
/// identity of every content package and a hash of every file in the game folder. Written by <c>mnvt build</c> and
/// signed (<see cref="SignatureFile"/>); the game verifies the signature with the public key compiled into it, then
/// opens exactly the packages listed, refusing any whose identity differs. Contains no timestamps or machine paths.
/// <code>
/// Game.exe, Game.dll, Game.runtimeconfig.json
/// Dependencies/Managed   engine and package assemblies
/// Dependencies/Native    native libraries (glfw3.dll, soft_oal.dll, vma.dll)
/// Dependencies/Runtime   private .NET runtime (host/fxr, shared/Microsoft.NETCore.App)
/// Game_Data/globals.mnvtpack           runtime configuration, asset index, C# game code
/// Game_Data/defaultresources.mnvtpack  engine-generated resources: precompiled shaders
/// Game_Data/level0.mnvtpack ...        one per scene (level0 = startup scene): the scene and assets only it uses
/// Game_Data/sharedassets.mnvtpack      assets used by several scenes
/// Game_Data/resources.mnvtpack         assets no scene references (loaded by path or GUID)
/// Game_Data/package.json, package.sig  build manifest and its signature
/// </code>
/// Packages are <c>.mnvtpack</c> files (MNVTEngine.IO.Packages); every file lives in exactly one.
/// </summary>
public sealed partial class GamePackage
{
    public const string ManifestFile = "package.json";

    /// <summary>Detached signature of <see cref="ManifestFile"/>: base64 of an ECDSA P-256 / SHA-256 signature of its exact bytes.</summary>
    public const string SignatureFile = "package.sig";

    public const string PackageExtension = ".mnvtpack";
    public const string GlobalsPackage = "globals" + PackageExtension;
    public const string DefaultResourcesPackage = "defaultresources" + PackageExtension;
    public const string SharedAssetsPackage = "sharedassets" + PackageExtension;
    public const string ResourcesPackage = "resources" + PackageExtension;
    public const string ManagedFolder = "Dependencies/Managed";
    public const string NativeFolder = "Dependencies/Native";
    public const string RuntimeFolder = "Dependencies/Runtime";
    public const string DataFolderSuffix = "_Data";
    public const string ScriptsEntryFolder = "Scripts/";

    /// <summary>Assembly metadata key of the game host that carries the package encryption key (masked, see <see cref="EmbeddedPackageKey"/>).</summary>
    public const string PackageKeyMetadata = "MNVTEngine.PackageKey";

    /// <summary>Assembly metadata key of the game host that carries the public key packages and the manifest must be signed with (hex SubjectPublicKeyInfo).</summary>
    public const string VerificationKeyMetadata = "MNVTEngine.PackageVerificationKey";

    /// <summary>2: .mnvtpack packages with identities, build id, signed manifest. Version 1 (.mnvtpak archives) is no longer readable: rebuild.</summary>
    public const int CurrentSchemaVersion = 2;

    public int SchemaVersion { get; set; } = CurrentSchemaVersion;

    public string Name { get; set; } = "";

    public string ExecutableName { get; set; } = "";

    public string Profile { get; set; } = "";

    public string Configuration { get; set; } = "";

    public string Target { get; set; } = "";

    /// <summary>The engine version the game was built with (MAJOR.DDMM.PATCH.BUILD[-label]); see <see cref="Engine"/>.</summary>
    public string EngineVersion { get; set; } = "";

    /// <summary>The engine build the game was built with; null in manifests of builds before engine versioning.</summary>
    public EngineBuildStamp? Engine { get; set; }

    /// <summary>Identity of this build: a hash of everything it was built from. Every package carries it.</summary>
    public Guid BuildId { get; set; }

    /// <summary>Id of the key that signed the packages and this manifest (public; for diagnostics).</summary>
    public string? SigningKeyId { get; set; }

    /// <summary>True when the in-game debug UI (and Dear ImGui) ships: Debug builds, or Release when the project opts in.</summary>
    public bool DevTools { get; set; }

    /// <summary>"jit" (IL assemblies on the private .NET runtime) or "aot" (one native executable, no runtime).</summary>
    public string ScriptingBackend { get; set; } = "jit";

    /// <summary>Engine modules built into the game, in startup order.</summary>
    public List<string>? Modules { get; set; }

    /// <summary>The game's C# code: package entry such as "Scripts/MyGame.Scripts.dll"; null without C# scripts.</summary>
    public string? ScriptsAssembly { get; set; }

    /// <summary>Content packages in mount order.</summary>
    public List<ContentPackage> Packages { get; set; } = [];

    /// <summary>Every file of the game folder with its hash, sorted by path; except the manifest, its signature and the packages (identified in <see cref="Packages"/>).</summary>
    public List<PackagedFile> Files { get; set; } = [];

    /// <summary>Package files to open, in order.</summary>
    [JsonIgnore]
    public IReadOnlyList<string> PackageFiles => [.. Packages.Select(a => a.File)];

    public static string LevelPackage(int index) => $"level{index}{PackageExtension}";

    /// <summary>
    /// Opens every content package of the game in <paramref name="dataDirectory"/> and checks that each is exactly the
    /// one this manifest lists (GUID, header hash and build id): packages cannot be swapped, even for other validly
    /// signed ones from another build.
    /// </summary>
    /// <exception cref="PackageException">A damaged, foreign, undecryptable or wrongly signed package.</exception>
    /// <exception cref="IOException">A package is missing or unreadable.</exception>
    public GameContent OpenContent(string dataDirectory, PackageOpenOptions options)
    {
        var content = GameContent.Open(dataDirectory, PackageFiles, options);
        try
        {
            foreach (var (listed, package) in Packages.Zip(content.Packages))
            {
                if (package.PackageGuid != listed.Guid || package.Info.BuildId != BuildId || !string.Equals(package.Info.HeaderSha256, listed.HeaderSha256, StringComparison.OrdinalIgnoreCase))
                {
                    throw new PackageException(PackageError.IntegrityFailure, $"{listed.File} is not the package this build shipped (replaced or from another build).");
                }
            }

            return content;
        }
        catch
        {
            content.Dispose();
            throw;
        }
    }

    /// <summary>The data folder of a game: <c>&lt;executable&gt;_Data</c>.</summary>
    public static string DataFolder(string executableName) => executableName + DataFolderSuffix;

    /// <summary>The <c>*_Data</c> folder holding a manifest inside <paramref name="gameDirectory"/>, or null if this is not an exported game.</summary>
    public static string? FindDataDirectory(string gameDirectory) =>
        Directory.Exists(gameDirectory)
            ? Directory.EnumerateDirectories(gameDirectory, "*" + DataFolderSuffix).FirstOrDefault(d => File.Exists(Path.Combine(d, ManifestFile)))
            : null;

    public static bool IsValidExecutableName(string name) => ExecutableNamePattern().IsMatch(name ?? "");

    /// <summary>Executable name derived from a project name: letters, digits, '_', '-' and '.' are kept; anything else is dropped.</summary>
    public static string ExecutableNameFor(string projectName)
    {
        ArgumentNullException.ThrowIfNull(projectName);
        var name = new string([.. projectName.Where(c => char.IsAsciiLetterOrDigit(c) || c is '_' or '-' or '.')]).TrimStart('-', '.', '_');
        while (name.Length > 0 && char.IsAsciiDigit(name[0]))
        {
            name = name[1..];
        }

        return name.Length > 0 ? name : "Game";
    }

    /// <summary>Reads the manifest; with <paramref name="trustedSigner"/>, only after its signature verifies.</summary>
    /// <param name="trustedSigner">The key the manifest must be signed with; null reads it unverified (tools).</param>
    /// <exception cref="SerializationException">The manifest is missing, malformed, unsigned or wrongly signed, or from another engine version.</exception>
    public static GamePackage Load(string dataDirectory, PackageVerificationKey? trustedSigner = null)
    {
        var file = Path.Combine(dataDirectory, ManifestFile);
        var diagnostics = new List<SerializationDiagnostic>();
        try
        {
            var bytes = File.ReadAllBytes(file);
            if (trustedSigner is not null && !VerifySignature(dataDirectory, bytes, trustedSigner))
            {
                throw new InvalidDataException($"The build manifest's signature ({SignatureFile}) is missing or does not match: the game files were modified.");
            }

            var document = JObject.Parse(System.Text.Encoding.UTF8.GetString(bytes));
            if (document.Value<int?>("schemaVersion") is < CurrentSchemaVersion)
            {
                throw new InvalidDataException("This game was built with an older MNVTEngine (content archives); rebuild it.");
            }

            new JsonMigrationPipeline(CurrentSchemaVersion).Migrate(document, diagnostics);
            var package = document.ToObject<GamePackage>(MnvtJson.CreateSerializer()) ?? throw new InvalidDataException("Manifest is empty.");
            if (package.ScriptsAssembly is { } scripts)
            {
                AssetPaths.Canonical(scripts); // refuses absolute or escaping paths
            }

            foreach (var listed in package.Packages)
            {
                if (Path.GetFileName(listed.File) != listed.File || !listed.File.EndsWith(PackageExtension, StringComparison.OrdinalIgnoreCase))
                {
                    throw new InvalidDataException($"'{listed.File}' is not a package file name.");
                }
            }

            return package;
        }
        catch (Exception ex) when (ex is JsonException or InvalidDataException or IOException or ArgumentException or FormatException)
        {
            throw new SerializationException(file, ex.Message, diagnostics, ex);
        }
    }

    /// <summary>True when <see cref="SignatureFile"/> holds a valid signature of <paramref name="manifest"/> by <paramref name="signer"/>.</summary>
    public static bool VerifySignature(string dataDirectory, byte[] manifest, PackageVerificationKey signer)
    {
        ArgumentNullException.ThrowIfNull(signer);
        var path = Path.Combine(dataDirectory, SignatureFile);
        try
        {
            return File.Exists(path) && signer.VerifyDetached(manifest, Convert.FromBase64String(File.ReadAllText(path).Trim()));
        }
        catch (FormatException)
        {
            return false; // not base64: as good as no signature
        }
    }

    /// <summary>Writes the manifest; with <paramref name="signer"/> also its signature.</summary>
    public void Save(string dataDirectory, PackageSigningKey? signer = null)
    {
        Files.Sort((a, b) => string.CompareOrdinal(a.Path, b.Path));
        var bytes = System.Text.Encoding.UTF8.GetBytes(JObject.FromObject(this, MnvtJson.CreateSerializer()).ToString(Formatting.Indented));
        File.WriteAllBytes(Path.Combine(dataDirectory, ManifestFile), bytes);
        if (signer is not null)
        {
            File.WriteAllText(Path.Combine(dataDirectory, SignatureFile), Convert.ToBase64String(DetachedSignature.Sign(signer, bytes)));
        }
    }

    [GeneratedRegex(@"^[A-Za-z][A-Za-z0-9_.\-]{0,63}$")]
    private static partial Regex ExecutableNamePattern();
}

/// <summary>The engine build an exported game was made with, as its signed manifest records it (docs/architecture/versioning.md).</summary>
public sealed class EngineBuildStamp
{
    /// <summary>MAJOR.DDMM.PATCH.BUILD with the prerelease label, like "1.1411.140.4-dev".</summary>
    public string Version { get; set; } = "";

    /// <summary>The executable's numeric file version, like "1.1411.140.4".</summary>
    public string FileVersion { get; set; } = "";

    /// <summary>Distinguishes two builds with the same version.</summary>
    public Guid BuildId { get; set; }

    /// <summary>The engine's Git commit; null when the engine was built without Git metadata.</summary>
    public string? Commit { get; set; }

    /// <summary>True when the engine was built from a modified working tree: not exactly <see cref="Commit"/>.</summary>
    public bool Dirty { get; set; }

    public DateTime TimestampUtc { get; set; }

    public string Channel { get; set; } = "";
}
