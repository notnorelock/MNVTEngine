using System.Globalization;
using System.Security;
using System.Text;
using Newtonsoft.Json;
using Newtonsoft.Json.Linq;

namespace MNVTEngine.Versioning;

/// <summary>
/// A version session folder: the resolved version of one logical build, in the forms its consumers read.
/// <list type="bullet">
/// <item><c>version.json</c>: the complete metadata (<see cref="EngineBuildInfo.ToJson"/>), readable without the engine;</item>
/// <item><c>version.props</c>: the MSBuild properties every engine project is stamped with (Directory.Build.targets);</item>
/// <item><c>EngineVersion.g.cs</c>: the values of <c>MNVTEngine.EngineVersion</c>, compiled into MNVTEngine.Core.</item>
/// </list>
/// Files are only rewritten when their content changes, so an unchanged version does not trigger recompilation.
/// </summary>
public static class VersionSession
{
    public const string MetadataFile = "version.json";
    public const string PropsFile = "version.props";
    public const string SourceFile = "EngineVersion.g.cs";

    /// <summary>The MSBuild property (or environment variable MNVT_VERSION_SESSION) that points builds at a session folder.</summary>
    public const string Property = "MnvtVersionSession";

    public static void Write(string directory, EngineBuildInfo info)
    {
        ArgumentNullException.ThrowIfNull(info);
        Directory.CreateDirectory(directory);
        WriteIfChanged(Path.Combine(directory, MetadataFile), info.ToJson().ToString(Formatting.Indented) + "\n");
        WriteIfChanged(Path.Combine(directory, PropsFile), Props(info));
        WriteIfChanged(Path.Combine(directory, SourceFile), Source(info));
    }

    /// <summary>The session's metadata; null when the folder has none.</summary>
    /// <exception cref="InvalidDataException">The metadata is damaged.</exception>
    public static EngineBuildInfo? Read(string directory)
    {
        var path = Path.Combine(directory, MetadataFile);
        if (!File.Exists(path))
        {
            return null;
        }

        try
        {
            return EngineBuildInfo.FromJson(JObject.Parse(File.ReadAllText(path)));
        }
        catch (JsonException ex)
        {
            throw new InvalidDataException($"{path} is damaged: {ex.Message}", ex);
        }
    }

    public static string Props(EngineBuildInfo info)
    {
        ArgumentNullException.ThrowIfNull(info);
        var text = new StringBuilder("<Project>\n  <!-- Generated by MNVTEngine.Versioning; do not edit. -->\n  <PropertyGroup>\n");
        void Property(string name, string value) => text.Append("    <").Append(name).Append('>').Append(SecurityElement.Escape(value)).Append("</").Append(name).Append(">\n");
        Property("MnvtVersion", info.Version);
        Property("MnvtPackageVersion", info.PackageVersion);
        Property("MnvtAssemblyVersion", info.AssemblyVersion);
        Property("MnvtFileVersion", info.FileVersion);
        Property("MnvtInformationalVersion", info.InformationalVersion);
        Property("MnvtBuildId", info.BuildId.ToString("D"));
        Property("MnvtCommit", info.Source.Commit ?? "unknown");
        Property("MnvtBuildTimestamp", info.TimestampUtc.ToString("yyyy-MM-ddTHH:mm:ssZ", CultureInfo.InvariantCulture));
        return text.Append("  </PropertyGroup>\n</Project>\n").ToString();
    }

    public static string Source(EngineBuildInfo info)
    {
        ArgumentNullException.ThrowIfNull(info);
        static string S(string? value) => value is null ? "null" : "\"" + Escape(value) + "\"";
        var b = CultureInfo.InvariantCulture;
        return $$"""
            // <auto-generated>
            // Generated by MNVTEngine.Versioning for this build; do not edit. See docs/architecture/versioning.md.
            // </auto-generated>
            #nullable enable

            namespace MNVTEngine;

            public static partial class EngineVersion
            {
                public static string Version => {{S(info.Version)}};

                public static string NumericVersion => {{S(info.NumericVersion)}};

                public static string InformationalVersion => {{S(info.InformationalVersion)}};

                public static int Major => {{info.Major.ToString(b)}};

                public static int Minor => {{info.Minor.ToString(b)}};

                public static string MinorText => {{S(info.MinorText)}};

                public static int Patch => {{info.Patch.ToString(b)}};

                public static int Build => {{info.Build.ToString(b)}};

                public static string Channel => {{S(info.Channel)}};

                public static string? Prerelease => {{S(info.Prerelease)}};

                public static string CommitHash => {{S(info.Source.Commit ?? "unknown")}};

                public static string Branch => {{S(info.Source.Branch ?? (info.Source.Detached ? "(detached)" : "unknown"))}};

                public static string? CommitSubject => {{S(info.Source.Subject)}};

                public static bool IsDirtyBuild => {{(info.Source.Dirty ? "true" : "false")}};

                public static string? SourceProblem => {{S(info.Source.Problem)}};

                public static global::System.DateTime BuildTimestampUtc => new({{info.TimestampUtc.UtcTicks.ToString(b)}}L, global::System.DateTimeKind.Utc);

                public static string BuildConfiguration => {{S(info.Context.Configuration ?? "unknown")}};

                public static string BuildId => {{S(info.BuildId.ToString("D"))}};

                public static string BuildKind => {{S(info.Kind)}};

                /// <summary>The complete metadata (the session's version.json).</summary>
                public static string MetadataJson => {{S(info.ToJson().ToString(Formatting.None))}};
            }

            """.Replace("\r\n", "\n", StringComparison.Ordinal);
    }

    private static string Escape(string value)
    {
        var text = new StringBuilder(value.Length);
        foreach (var c in value)
        {
            _ = c switch
            {
                '"' => text.Append("\\\""),
                '\\' => text.Append("\\\\"),
                '\n' => text.Append("\\n"),
                '\r' => text.Append("\\r"),
                '\t' => text.Append("\\t"),
                < ' ' or (char)0x2028 or (char)0x2029 => text.Append("\\u").Append(((int)c).ToString("x4", CultureInfo.InvariantCulture)),
                _ => text.Append(c),
            };
        }

        return text.ToString();
    }

    private static void WriteIfChanged(string path, string content)
    {
        if (File.Exists(path) && File.ReadAllText(path) == content)
        {
            return;
        }

        var temporary = $"{path}.{Environment.ProcessId}.tmp";
        File.WriteAllText(temporary, content, new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
        for (var attempt = 1; ; attempt++)
        {
            try
            {
                File.Move(temporary, path, overwrite: true); // atomic: a parallel build reads the old or the new file, never half of one
                return;
            }
            catch (Exception ex) when ((ex is IOException or UnauthorizedAccessException) && attempt < 20)
            {
                Thread.Sleep(50); // a compiler of a parallel build is reading the file
            }
        }
    }
}
