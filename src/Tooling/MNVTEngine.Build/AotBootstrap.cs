using System.Reflection;
using System.Text;
using MNVTEngine.Modules;
using MNVTEngine.Scenes;

namespace MNVTEngine.Build;

/// <summary>
/// The ahead-of-time (NativeAOT) additions to the <see cref="ModuleBootstrap"/>: the host is published with
/// <c>PublishAot</c>, the game's C# assembly is referenced and compiled into the executable, and two kinds of
/// preservation replace what the JIT host does at run time:
/// <list type="bullet">
/// <item><c>GameComponents.g.cs</c> registers every game component with <c>Register&lt;T&gt;()</c>: no assembly loading
/// and no type scanning.</item>
/// <item>The same file instantiates the generic collections over value types that the scene serializer creates by
/// reflection (<c>List&lt;TileCell&gt;</c>, <c>ReadOnlyCollection&lt;TileCell&gt;</c>, arrays, dictionaries), found from the
/// serializable members of every component in the game: native code for them exists only if some code names them.</item>
/// <item>The assemblies of the game's modules, the game's assembly and Newtonsoft.Json are trimmer roots (see
/// <see cref="Roots"/>): their metadata is kept whole, because components, project files and settings are
/// (de)serialized by reflection.</item>
/// </list>
/// </summary>
public static class AotBootstrap
{
    public const string SourceFile = "GameComponents.g.cs";

    /// <summary>
    /// Assemblies kept whole: every assembly of the game's modules (engine and third-party: physics engines create
    /// their solvers by reflection), the game's code and the JSON serializer. The interop bindings (Silk.NET, Vortice)
    /// are not rooted: they are large, call native code directly and need no reflection.
    /// </summary>
    public static IReadOnlyList<string> Roots(ModuleResolution resolution, string? scriptsAssemblyName, IEnumerable<string>? dlcAssemblyNames = null)
    {
        ArgumentNullException.ThrowIfNull(resolution);
        return [.. resolution.Modules.SelectMany(m => m.RuntimeAssemblies).Where(a => !a.StartsWith("Silk.NET.", StringComparison.Ordinal) && !a.StartsWith("Vortice.", StringComparison.Ordinal))
            .Append("Newtonsoft.Json").Concat(scriptsAssemblyName is null ? [] : [scriptsAssemblyName]).Concat(dlcAssemblyNames ?? [])
            .Distinct(StringComparer.Ordinal).Order(StringComparer.Ordinal)];
    }

    /// <param name="gameComponents">The game's component types (registered in this order).</param>
    /// <param name="engineComponents">Component types of the game's modules, for their serializable members.</param>
    /// <param name="dlcComponents">DLC name to its code's component types: registered by <c>RegisterDlc</c> once that DLC is mounted.</param>
    public static string Source(IReadOnlyList<Type> gameComponents, IEnumerable<Type> engineComponents, IReadOnlyDictionary<string, IReadOnlyList<Type>>? dlcComponents = null)
    {
        ArgumentNullException.ThrowIfNull(gameComponents);
        dlcComponents ??= new Dictionary<string, IReadOnlyList<Type>>();
        var text = new StringBuilder();
        text.Append("// <auto-generated>\n// Generated by mnvt build for the ahead-of-time scripting backend.\n// </auto-generated>\n")
            .Append("namespace MNVTEngine.GameHost;\n\n")
            .Append("internal static class GameComponents\n{\n")
            .Append("    public static void Register(global::MNVTEngine.Scenes.ComponentRegistry registry)\n    {\n")
            .Append("        global::System.GC.KeepAlive((global::System.Action)KeepGenericInstantiations);\n");
        foreach (var type in gameComponents)
        {
            text.Append("        registry.Register<").Append(Name(type)).Append(">();\n");
        }

        text.Append("    }\n\n")
            .Append("    /// <summary>Registers the components of a DLC's code; false when this build does not contain that DLC's code.</summary>\n")
            .Append("    public static bool RegisterDlc(global::MNVTEngine.Scenes.ComponentRegistry registry, string dlc)\n    {\n")
            .Append("        switch (dlc)\n        {\n");
        foreach (var (dlc, types) in dlcComponents.OrderBy(d => d.Key, StringComparer.Ordinal))
        {
            text.Append("            case \"").Append(dlc).Append("\":\n");
            foreach (var type in types)
            {
                text.Append("                registry.Register<").Append(Name(type)).Append(">();\n");
            }

            text.Append("                return true;\n");
        }

        text.Append("            default:\n                return false;\n        }\n    }\n\n")
            .Append("    // Never called: names the collections the serializer creates by reflection, so the AOT compiler generates their code.\n")
            .Append("    private static void KeepGenericInstantiations()\n    {\n");
        foreach (var line in Instantiations(gameComponents.Concat(dlcComponents.Values.SelectMany(t => t)).Concat(engineComponents)))
        {
            text.Append("        ").Append(line).Append('\n');
        }

        return text.Append("    }\n}\n").ToString();
    }

    /// <summary>Statements that create each closed generic collection over value types reachable from the components' serialized members.</summary>
    public static IReadOnlyList<string> Instantiations(IEnumerable<Type> components)
    {
        ArgumentNullException.ThrowIfNull(components);
        var elements = new SortedSet<string>(StringComparer.Ordinal);
        var dictionaries = new SortedSet<string>(StringComparer.Ordinal);
        var visited = new HashSet<Type>();

        void Visit(Type type, int depth)
        {
            if (depth > 8 || !visited.Add(type) || type.IsPrimitive || type == typeof(string) || type.IsEnum)
            {
                return;
            }

            if (type.IsArray && type.GetElementType() is { } arrayElement)
            {
                Element(arrayElement, depth);
                return;
            }

            if (type.IsGenericType)
            {
                var arguments = type.GetGenericArguments();
                var definition = type.GetGenericTypeDefinition();
                if (arguments.Length == 2 && (definition == typeof(Dictionary<,>) || definition == typeof(IDictionary<,>) || definition == typeof(IReadOnlyDictionary<,>)))
                {
                    if (arguments.Any(a => a.IsValueType))
                    {
                        dictionaries.Add($"{Name(arguments[0])}, {Name(arguments[1])}");
                    }

                    Visit(arguments[1], depth + 1);
                    return;
                }

                if (arguments.Length == 1 && typeof(System.Collections.IEnumerable).IsAssignableFrom(type))
                {
                    Element(arguments[0], depth);
                    return;
                }
            }

            // A plain data type nested in a component: its public fields and settable properties are serialized too.
            if (!typeof(Component).IsAssignableFrom(type) && (type.IsValueType || type.IsClass) && type.Assembly.GetName().Name is { } assembly
                && !assembly.StartsWith("System", StringComparison.Ordinal) && assembly != "Newtonsoft.Json")
            {
                foreach (var member in type.GetFields(BindingFlags.Public | BindingFlags.Instance).Select(f => f.FieldType)
                    .Concat(type.GetProperties(BindingFlags.Public | BindingFlags.Instance).Where(p => p.CanWrite).Select(p => p.PropertyType)))
                {
                    Visit(member, depth + 1);
                }
            }
        }

        void Element(Type element, int depth)
        {
            if (element.IsValueType && !element.ContainsGenericParameters)
            {
                elements.Add(Name(element));
            }

            Visit(element, depth + 1);
        }

        foreach (var component in components.Where(c => typeof(Component).IsAssignableFrom(c) && !c.IsAbstract))
        {
            foreach (var member in ComponentTypeInfo.Get(component).SerializableMembers)
            {
                Visit(member switch { FieldInfo f => f.FieldType, PropertyInfo p => p.PropertyType, _ => typeof(object) }, 0);
            }
        }

        var lines = new List<string>();
        foreach (var (element, i) in elements.Select((e, i) => (e, i)))
        {
            lines.Add($"var list{i} = new global::System.Collections.Generic.List<{element}>();");
            lines.Add($"_ = new global::System.Collections.ObjectModel.ReadOnlyCollection<{element}>(list{i});");
            lines.Add($"_ = list{i}.ToArray();");
        }

        lines.AddRange(dictionaries.Select(d => $"_ = new global::System.Collections.Generic.Dictionary<{d}>();"));
        return lines;
    }

    /// <summary>The C# name of a closed type, fully qualified.</summary>
    public static string Name(Type type)
    {
        ArgumentNullException.ThrowIfNull(type);
        if (type.IsArray)
        {
            return Name(type.GetElementType()!) + "[" + new string(',', type.GetArrayRank() - 1) + "]";
        }

        var name = type.Name;
        var tick = name.IndexOf('`', StringComparison.Ordinal);
        if (tick >= 0)
        {
            name = name[..tick];
        }

        var own = type.IsGenericType
            ? type.GetGenericArguments().Skip(type.DeclaringType?.GetGenericArguments().Length ?? 0).ToList()
            : [];
        var suffix = own.Count > 0 ? "<" + string.Join(", ", own.Select(Name)) + ">" : "";
        return type.DeclaringType is { } declaring
            ? Name(declaring) + "." + name + suffix
            : "global::" + (string.IsNullOrEmpty(type.Namespace) ? "" : type.Namespace + ".") + name + suffix;
    }
}
