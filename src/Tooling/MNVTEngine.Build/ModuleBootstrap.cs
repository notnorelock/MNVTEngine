using System.Text;
using MNVTEngine.Modules;

namespace MNVTEngine.Build;

/// <summary>
/// Generates the game host's module bootstrap from a build's resolved modules: <c>ModuleBootstrap.g.cs</c>, which
/// creates exactly those modules (explicit constructor calls in startup order: no reflection, no assembly scanning, so
/// it stays trimming- and AOT-friendly), and <c>ModuleBootstrap.g.props</c>, which references only their projects and
/// replaces the host's development list (<c>HostModules.cs</c>). <c>dotnet publish</c> of GameHost imports the props
/// through <c>-p:MnvtBootstrap</c>; assemblies of modules the game does not use are then not built into it at all.
/// </summary>
public static class ModuleBootstrap
{
    public const string SourceFile = "ModuleBootstrap.g.cs";
    public const string PropsFile = "ModuleBootstrap.g.props";

    /// <summary>The C# that creates a module (with <c>logger</c> in scope) and the engine projects it needs.</summary>
    private sealed record Entry(string Expression, string[] Projects);

    private static readonly Dictionary<string, Entry> Entries = new(StringComparer.Ordinal)
    {
        ["audio"] = new("new global::MNVTEngine.AudioModule(global::MNVTEngine.Audio.OpenAL.OpenALAudioDevice.Create, logger)", ["MNVTEngine.Audio", "MNVTEngine.Audio.OpenAL"]),
        ["physics.2d"] = new("new global::MNVTEngine.Physics2DModule()", ["MNVTEngine.Physics2D"]),
        ["physics.3d"] = new("new global::MNVTEngine.Physics3DModule()", ["MNVTEngine.Physics3D"]),
        ["scripting"] = new("new global::MNVTEngine.ScriptingModule()", ["MNVTEngine.Scripting.Bindings"]),
        ["terrain"] = new("new global::MNVTEngine.TerrainModule()", ["MNVTEngine.Terrain.Components"]),
        ["ui"] = new("new global::MNVTEngine.UI.UIModule()", ["MNVTEngine.UI"]),
        ["world.2d"] = new("new global::MNVTEngine.World2D.Rendering.World2DModule()", ["MNVTEngine.World2D.Rendering"]),
        ["world.3d"] = new("new global::MNVTEngine.World3D.Rendering.World3DModule()", ["MNVTEngine.World3D.Rendering"]),
    };

    /// <summary>Modules with a runtime implementation the host creates; the others (core, graphics, ...) are the host itself.</summary>
    public static IReadOnlyCollection<string> ImplementedModules => Entries.Keys;

    /// <summary>Engine projects (names) the host references for these modules, in order.</summary>
    public static IReadOnlyList<string> Projects(IEnumerable<string> moduleIds) =>
        [.. moduleIds.Where(Entries.ContainsKey).SelectMany(id => Entries[id].Projects).Distinct(StringComparer.Ordinal).Order(StringComparer.Ordinal)];

    public static string Source(ModuleResolution resolution)
    {
        ArgumentNullException.ThrowIfNull(resolution);
        var modules = resolution.Modules.Where(m => Entries.ContainsKey(m.Id)).ToList();
        var text = new StringBuilder();
        text.Append("// <auto-generated>\n")
            .Append("// Generated by mnvt build from the project's resolved modules (").Append(resolution.Profile.DisplayName()).Append("): ")
            .Append(string.Join(", ", resolution.Modules.Select(m => m.Id))).Append(".\n")
            .Append("// </auto-generated>\n")
            .Append("namespace MNVTEngine.GameHost;\n\n")
            .Append("/// <summary>The engine modules built into this game, in startup order.</summary>\n")
            .Append("internal static class HostModules\n{\n")
            .Append("    public static global::System.Collections.Generic.IReadOnlyList<global::MNVTEngine.Scenes.IEngineModule> Create(global::Microsoft.Extensions.Logging.ILogger logger)\n    {\n");
        if (!modules.Any(m => Entries[m.Id].Expression.Contains("logger", StringComparison.Ordinal)))
        {
            text.Append("        _ = logger;\n");
        }

        text.Append("        return\n        [\n");
        foreach (var module in modules)
        {
            text.Append("            ").Append(Entries[module.Id].Expression).Append(",\n");
        }

        return text.Append("        ];\n    }\n}\n").ToString();
    }

    /// <param name="sourcePath">Where <see cref="Source"/> was written.</param>
    public static string Props(ModuleResolution resolution, string sourcePath)
    {
        ArgumentNullException.ThrowIfNull(resolution);
        var text = new StringBuilder();
        text.Append("<Project>\n  <!-- Generated by mnvt build: the modules of this game only. -->\n  <ItemGroup>\n")
            .Append("    <Compile Remove=\"HostModules.cs\" />\n")
            .Append("    <Compile Include=\"").Append(System.Security.SecurityElement.Escape(sourcePath)).Append("\" />\n");
        foreach (var project in Projects(resolution.Modules.Select(m => m.Id)))
        {
            text.Append("    <ProjectReference Include=\"$(MSBuildProjectDirectory)\\..\\").Append(project).Append('\\').Append(project)
                .Append(".csproj\" GlobalPropertiesToRemove=\"$(MnvtGameProperties)\" />\n");
        }

        return text.Append("  </ItemGroup>\n</Project>\n").ToString();
    }

    /// <summary>Writes both files into <paramref name="directory"/> and returns the props path for <c>-p:MnvtBootstrap</c>.</summary>
    public static string Write(ModuleResolution resolution, string directory)
    {
        Directory.CreateDirectory(directory);
        var source = Path.Combine(directory, SourceFile);
        var props = Path.Combine(directory, PropsFile);
        File.WriteAllText(source, Source(resolution));
        File.WriteAllText(props, Props(resolution, source));
        return props;
    }
}
